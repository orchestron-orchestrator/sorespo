// Generates src/sorespo/webui_assets.act from the static web UI build in
// webui/build, embedding every asset as a base64 string constant (the
// StratoWeave HTTP server serves str bodies, so only text assets embed; the
// base64 alphabet is immune to Acton string-literal escaping/interpolation).
//
// Run via `make gen-webui` (which builds the UI first). The output is
// committed to git; CI regenerates it and fails on any diff, so the build
// must stay byte-deterministic (see kit.version in svelte.config.js).

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const BUILD_DIR = fileURLToPath(new URL('../build', import.meta.url));
const OUT_FILE = fileURLToPath(new URL('../../src/sorespo/webui_assets.act', import.meta.url));

// Only known-text formats may be embedded. Anything else is a hard error so
// a stray binary can never silently corrupt the served UI.
const TEXT_EXTENSIONS = new Set([
  '.html', '.js', '.mjs', '.css', '.json', '.map', '.svg', '.txt', '.xml', '.webmanifest'
]);
const BINARY_HINTS = new Set([
  '.png', '.jpg', '.jpeg', '.gif', '.ico', '.avif', '.webp',
  '.woff', '.woff2', '.ttf', '.otf', '.eot',
  '.gz', '.br', '.zip', '.wasm'
]);

function fail(message) {
  console.error(`gen-embedded-assets: ${message}`);
  process.exit(1);
}

function walk(dir) {
  let files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      files = files.concat(walk(path));
    } else if (entry.isFile()) {
      files.push(path);
    } else {
      fail(`unsupported directory entry: ${path}`);
    }
  }
  return files;
}

if (!existsSync(BUILD_DIR)) {
  fail(`missing ${BUILD_DIR} — run \`make gen-webui\` (or \`bun run build\` first)`);
}

const files = walk(BUILD_DIR).sort();
if (files.length === 0) {
  fail(`no files under ${BUILD_DIR}`);
}

const utf8 = new TextDecoder('utf-8', { fatal: true });
const entries = [];
let totalBytes = 0;

for (const file of files) {
  const urlPath = '/' + relative(BUILD_DIR, file).split(sep).join('/');
  if (!/^[A-Za-z0-9._/-]+$/.test(urlPath)) {
    fail(`${urlPath}: unexpected characters in asset path`);
  }

  const ext = extname(file).toLowerCase();
  if (!TEXT_EXTENSIONS.has(ext)) {
    if (BINARY_HINTS.has(ext)) {
      fail(
        `${urlPath}: binary/precompressed assets cannot be embedded (the HTTP ` +
          `server sends str bodies only) — inline it into the bundle (data URI) or drop it`
      );
    }
    fail(`${urlPath}: extension "${ext}" is not in the embed whitelist; add it here if it is a text format`);
  }

  const buf = readFileSync(file);
  if (buf.length === 0) {
    fail(`${urlPath}: empty file in build output`);
  }
  try {
    utf8.decode(buf);
  } catch {
    fail(`${urlPath}: not valid UTF-8 — only text assets can be embedded`);
  }

  totalBytes += buf.length;
  entries.push({ urlPath, b64: buf.toString('base64') });
}

const wrap = (b64) => b64.replace(/(.{120})/g, '$1\n');

const out = [];
out.push('# Embedded SORESPO Web UI: the static webui build as base64 string constants.');
out.push('# Generated by webui/scripts/gen-embedded-assets.mjs via `make gen-webui`. DO NOT EDIT.');
out.push(`# ${entries.length} assets, ${totalBytes} bytes raw.`);
out.push('');
out.push('import base64');
out.push('');
entries.forEach((entry, i) => {
  out.push('');
  out.push(`# ${entry.urlPath}`);
  out.push(`_B64_${i} = r"""`);
  out.push(wrap(entry.b64));
  out.push('"""');
});
out.push('');
out.push('');
out.push('def _d(data: str) -> str:');
out.push('    return base64.decode("".join(data.split("\\n")).encode()).decode()');
out.push('');
out.push('');
out.push('def assets() -> dict[str, str]:');
out.push('    """The built web UI as a URL path -> file content map."""');
out.push('    a: dict[str, str] = {}');
entries.forEach((entry, i) => {
  out.push(`    a["${entry.urlPath}"] = _d(_B64_${i})`);
});
out.push('    return a');
out.push('');

writeFileSync(OUT_FILE, out.join('\n'));
console.log(`gen-embedded-assets: wrote ${OUT_FILE} (${entries.length} assets, ${totalBytes} bytes raw)`);
